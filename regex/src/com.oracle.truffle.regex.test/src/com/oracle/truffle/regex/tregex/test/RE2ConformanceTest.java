package com.oracle.truffle.regex.tregex.test;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;

import org.graalvm.polyglot.PolyglotException;
import org.graalvm.polyglot.Value;
import org.junit.Assert;
import org.junit.Test;

import com.oracle.truffle.regex.tregex.string.Encoding;

/**
 * Runs RE2's search test cases against the RE2 flavor.
 * <p>
 * The test data in {@code re2data/re2-search.txt} is an unmodified copy of
 * {@code src/regexp/testdata/re2-search.txt} from the Go project (https://github.com/golang/go),
 * which was in turn generated by RE2's test suite. It is distributed under the BSD-style license
 * in {@code re2data/LICENSE}. The file format is documented in Go's
 * {@code src/regexp/exec_test.go}: every regex is followed by one result line per input string,
 * each holding four semicolon-separated results: full match, partial (search) match, full
 * longest match and partial longest match. Positions are UTF-8 byte offsets.
 * <p>
 * TRegex implements RE2's default leftmost-first semantics, so the full and partial match
 * results are checked (in UTF-8 and in UTF-16, with offsets converted to UTF-16 code units),
 * while the two leftmost-longest results are skipped and counted. Regexes that contain RE2's
 * {@code \C} (match a single byte), which TRegex does not support, are expected to cause a syntax
 * error instead.
 */
public class RE2ConformanceTest extends RegexTestBase {

    private static final String TEST_DATA = "re2data/re2-search.txt";

    private static final String[] MODE_NAMES = {"full", "partial", "full-longest", "partial-longest"};

    @Override
    Map<String, String> getEngineOptions() {
        return RE2Tests.ENGINE_OPTIONS;
    }

    @Override
    Encoding getTRegexEncoding() {
        return Encoding.UTF_16;
    }

    private record Stats(int[] counts) {
        Stats() {
            this(new int[5]);
        }
    }

    private static final int CHECKED = 0;
    private static final int PASSED = 1;
    private static final int SKIPPED_LONGEST = 2;
    private static final int SKIPPED_ANY_BYTE = 3;
    private static final int SKIPPED_NON_ASCII_NOT_WORD_BOUNDARY = 4;

    @Test
    public void re2SearchUTF8() throws IOException {
        runTestFile(Encoding.UTF_8);
    }

    @Test
    public void re2SearchUTF16() throws IOException {
        runTestFile(Encoding.UTF_16);
    }

    private void runTestFile(Encoding encoding) throws IOException {
        List<String> lines = readTestData();
        List<String> strings = new ArrayList<>();
        List<String> failures = new ArrayList<>();
        Stats stats = new Stats();
        boolean inStrings = false;
        String regex = null;
        Value[] compiled = null;
        int inputIndex = 0;
        for (int lineNo = 1; lineNo <= lines.size(); lineNo++) {
            String line = lines.get(lineNo - 1);
            if (line.isEmpty() || line.charAt(0) == '#' || ('A' <= line.charAt(0) && line.charAt(0) <= 'Z')) {
                continue;
            }
            if (line.equals("strings")) {
                strings.clear();
                inStrings = true;
            } else if (line.equals("regexps")) {
                inStrings = false;
            } else if (line.charAt(0) == '"') {
                String q = unquote(line);
                if (inStrings) {
                    strings.add(q);
                    continue;
                }
                regex = q;
                inputIndex = 0;
                if (regex.contains("\\C")) {
                    expectSyntaxError(context, regex, "", options(), encoding, "\\C", Integer.MIN_VALUE);
                    compiled = null;
                } else {
                    compiled = new Value[]{compileRegex(context, "\\A(?:" + regex + ")\\z", "", options(), encoding), compileRegex(context, regex, "", options(), encoding)};
                    for (Value v : compiled) {
                        Assert.assertFalse("regex " + regex + " is not supported", v.isNull());
                        Assert.assertFalse("regex " + regex + " uses the backtracking engine", v.getMember("isBacktracking").asBoolean());
                    }
                }
            } else if (line.charAt(0) == '-' || Character.isDigit(line.charAt(0))) {
                String text = strings.get(inputIndex++);
                String[] results = line.split(";");
                Assert.assertEquals(4, results.length);
                stats.counts[SKIPPED_LONGEST] += 2;
                if (compiled == null) {
                    stats.counts[SKIPPED_ANY_BYTE] += 2;
                    continue;
                }
                if (regex.contains("\\B") && !text.chars().allMatch(c -> c < 0x80)) {
                    // RE2 considers \B at every byte position, even inside of multi-byte UTF-8
                    // sequences. TRegex (like Go's regexp package) only considers positions
                    // between code points.
                    stats.counts[SKIPPED_NON_ASCII_NOT_WORD_BOUNDARY] += 2;
                    continue;
                }
                for (int mode = 0; mode < 2; mode++) {
                    String id = lineNo + ":" + MODE_NAMES[mode];
                    stats.counts[CHECKED]++;
                    int[] expected = convertOffsets(parseResult(results[mode]), text, encoding);
                    String actual = run(compiled[mode], encoding, text);
                    String expectedStr = expected == null ? "-" : Arrays.toString(expected);
                    if (actual.equals(expectedStr)) {
                        stats.counts[PASSED]++;
                    } else {
                        failures.add(String.format("%s: /%s/ %s on \"%s\": expected %s, actual %s", id, regex, MODE_NAMES[mode], escape(text), expectedStr, actual));
                    }
                }
            } else {
                Assert.fail("unexpected line " + lineNo + ": " + line);
            }
        }
        System.out.printf("%nRE2 conformance (%s): %d checked, %d passed, %d longest-match skipped, %d \\C skipped, %d non-ASCII \\B skipped%n",
                        encoding.getName(), stats.counts[CHECKED], stats.counts[PASSED], stats.counts[SKIPPED_LONGEST], stats.counts[SKIPPED_ANY_BYTE],
                        stats.counts[SKIPPED_NON_ASCII_NOT_WORD_BOUNDARY]);
        if (!failures.isEmpty()) {
            Assert.fail(failures.size() + " RE2 conformance failures:\n" + String.join("\n", new TreeSet<>(failures)));
        }
    }

    private static String run(Value compiledRegex, Encoding encoding, String text) {
        Value result = execRegex(compiledRegex, encoding, text, 0);
        boolean booleanResult = execRegexBoolean(compiledRegex, encoding, text, 0).asBoolean();
        if (booleanResult != result.getMember("isMatch").asBoolean()) {
            return "inconsistent boolean result: " + booleanResult;
        }
        if (!result.getMember("isMatch").asBoolean()) {
            return "-";
        }
        int groupCount = compiledRegex.getMember("groupCount").asInt();
        int[] actual = new int[groupCount * 2];
        for (int i = 0; i < groupCount; i++) {
            actual[2 * i] = result.invokeMember("getStart", i).asInt();
            actual[2 * i + 1] = result.invokeMember("getEnd", i).asInt();
        }
        return Arrays.toString(actual);
    }

    private static List<String> readTestData() throws IOException {
        try (InputStream in = RE2ConformanceTest.class.getResourceAsStream(TEST_DATA)) {
            Assert.assertNotNull("missing test resource " + TEST_DATA, in);
            List<String> lines = new ArrayList<>();
            try (BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
                String line;
                while ((line = reader.readLine()) != null) {
                    lines.add(line);
                }
            }
            return lines;
        }
    }

    /**
     * Parses a result in the format of Go's {@code parseResult}: {@code -} for no match, or a
     * space-separated list of {@code lo-hi} pairs, where {@code -} denotes an unmatched group.
     */
    private static int[] parseResult(String res) {
        if (res.equals("-")) {
            return null;
        }
        String[] pairs = res.split(" ");
        int[] out = new int[pairs.length * 2];
        for (int i = 0; i < pairs.length; i++) {
            if (pairs[i].equals("-")) {
                out[2 * i] = -1;
                out[2 * i + 1] = -1;
            } else {
                int dash = pairs[i].indexOf('-');
                out[2 * i] = Integer.parseInt(pairs[i].substring(0, dash));
                out[2 * i + 1] = Integer.parseInt(pairs[i].substring(dash + 1));
            }
        }
        return out;
    }

    /**
     * Converts UTF-8 byte offsets to offsets in the given encoding.
     */
    private static int[] convertOffsets(int[] utf8Offsets, String text, Encoding encoding) {
        if (utf8Offsets == null || encoding == Encoding.UTF_8) {
            return utf8Offsets;
        }
        assert encoding == Encoding.UTF_16;
        byte[] bytes = text.getBytes(StandardCharsets.UTF_8);
        int[] byteToChar = new int[bytes.length + 1];
        Arrays.fill(byteToChar, -1);
        int byteIndex = 0;
        for (int charIndex = 0; charIndex < text.length();) {
            int c = text.codePointAt(charIndex);
            byteToChar[byteIndex] = charIndex;
            byteIndex += new String(Character.toChars(c)).getBytes(StandardCharsets.UTF_8).length;
            charIndex += Character.charCount(c);
        }
        byteToChar[bytes.length] = text.length();
        int[] result = new int[utf8Offsets.length];
        for (int i = 0; i < utf8Offsets.length; i++) {
            if (utf8Offsets[i] < 0) {
                result[i] = -1;
            } else {
                result[i] = byteToChar[utf8Offsets[i]];
                Assert.assertTrue("offset is not at a code point boundary", result[i] >= 0);
            }
        }
        return result;
    }

    /**
     * Unquotes a Go double-quoted string literal. The test data only uses the {@code \\},
     * {@code \"} and {@code \n} escapes.
     */
    private static String unquote(String quoted) {
        Assert.assertTrue(quoted.length() >= 2 && quoted.charAt(0) == '"' && quoted.charAt(quoted.length() - 1) == '"');
        StringBuilder sb = new StringBuilder();
        int i = 1;
        while (i < quoted.length() - 1) {
            char c = quoted.charAt(i++);
            if (c == '\\') {
                char e = quoted.charAt(i++);
                switch (e) {
                    case '\\':
                    case '"':
                        sb.append(e);
                        break;
                    case 'n':
                        sb.append('\n');
                        break;
                    case 't':
                        sb.append('\t');
                        break;
                    default:
                        Assert.fail("unsupported escape in Go string literal: " + quoted);
                }
            } else {
                sb.append(c);
            }
        }
        return sb.toString();
    }

    private static String escape(String s) {
        return s.replace("\n", "\\n");
    }

    @Test
    public void unsupportedAnyByte() {
        try {
            compileRegex("a\\C*", "");
            Assert.fail("expected syntax error");
        } catch (PolyglotException e) {
            Assert.assertTrue(e.isSyntaxError());
        }
    }
}
